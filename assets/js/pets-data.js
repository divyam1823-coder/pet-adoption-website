// Helper functions to fetch pets
function getAllPets() {
  return petsData;
}

function getFeaturedPets() {
  return petsData.filter(pet => pet.featured);
}

function getPetById(id) {
  if (!id) return null;
  return petsData.find(pet => pet.id.toLowerCase() === id.toLowerCase()) || null;
}
